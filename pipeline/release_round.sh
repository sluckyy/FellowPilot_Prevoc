#!/usr/bin/env bash
# After a round is generated and critiqued: run the gates, build review docs, and write the items that
# passed every automated check as a migration (the beta loads them on deploy, unreviewed, tagged
# "AI-reviewed, not yet clinically reviewed"). Also refreshes the browser-test fixture.
#
#   pipeline/release_round.sh 1 008
set -euo pipefail
round="${1:?round number}"; mig="${2:?migration number, e.g. 008}"
here="$(cd "$(dirname "$0")" && pwd)"; root="$(cd "$here/.." && pwd)"
rd="$here/rounds/round$round"
cd "$here"
python3 gates.py --round-dir "$rd" | head -40
python3 to_review_docs.py --round-dir "$rd" --out "$rd/review_docs.json"
cd "$root/packages/core" && npm run build --silent
node dist/src/cli/load-beta.js --docs "$rd/review_docs.json" --out "$rd/beta.sql" --report "$rd/beta_report.json" | tee "$rd/beta_summary.txt"
{
  echo "-- Round $round question bank, released to the beta before clinical review (pipeline/release_round.sh)."
  echo "-- Every item passed the automated gates and an independent AI critic; review_level is 'none' and the app"
  echo "-- shows an \"AI-reviewed, not yet clinically reviewed\" tag. Reviewed versions are added on top later."
  cat "$rd/beta.sql"
} > "$root/db/migrations/${mig}_round${round}_beta_items.sql"
# Browser-test fixture: the first 12 released items (the suite expects 12).
node -e '
const fs = require("fs");
const sql = fs.readFileSync(process.argv[1], "utf8");
const blocks = sql.split(/\n(?=INSERT INTO item \()/).filter((b) => b.startsWith("INSERT INTO item ("));
const picked = blocks.slice(0, 12).map((b) => b.replace(/COMMIT;\s*$/, "").trim());
fs.writeFileSync(process.argv[2], "-- Test fixture: 12 round '"$round"' questions released to the beta. Generated by pipeline/release_round.sh; test use only.\nBEGIN;\n" + picked.join("\n") + "\nCOMMIT;\n");
console.log("fixture items:", picked.length);
' "$rd/beta.sql" "$root/apps/web/e2e/fixtures/items.sql"
echo "wrote db/migrations/${mig}_round${round}_beta_items.sql"
